local LOCALES = { enUS = enUS, frFR = frFR }
local SPECS = { frFR = SPECS_frFR }
local PROFESSIONS = { frFR = PROFESSIONS_frFR }
local active, activeSpecs, activeProfessions

function ns.SetLocale(code)
    active = LOCALES[code] or enUS
    activeSpecs = SPECS[code]
    activeProfessions = PROFESSIONS[code]
end

ns.SetLocale(GetLocale and GetLocale() or "enUS")

ns.L = setmetatable({}, {
    __index = function(_, key)
        return active[key] or enUS[key] or key
    end,
})

-- A spec's name in the game's language (the English one when it has no translation).
function ns.SpecName(english)
    return (activeSpecs and activeSpecs[english]) or english
end

function ns.ProfessionName(english)
    return (activeProfessions and activeProfessions[english]) or english
end

