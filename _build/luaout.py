"""Write Easy BIS's data files (Lua) from the ranked ladders.

The data is kept as text blocks that the addon decodes on first use, so loading
the addon stays cheap. Every file starts with ForeverDB's credit line, which
its licence asks to keep (GPL-3.0 section 7(b), see NOTICE.txt).
"""
from __future__ import annotations

from pathlib import Path

import ladders
import phases

CREDIT = "Data from ForeverDB.net (https://foreverdb.net)"
ENCHANTS_PER_SLOT = 3
SOURCES_PER_ITEM = 2
CLOSING = "]==]"


def _block(lines) -> str:
    text = "\n".join(lines)
    if CLOSING in text:
        raise ValueError("data contains the long-string closing bracket")
    return "[==[\n" + text + "\n" + CLOSING


def _field(text: str) -> str:
    """A value that goes between `|` separators on one line."""
    if "|" in text or "\n" in text or "\t" in text:
        raise ValueError(f"unexpected separator in {text!r}")
    return text


def _header(db, what: str, legend=()) -> list[str]:
    lines = [
        db.header,
        f"-- Generated by _build/build.py (Easy BIS) from ForeverDB's addon data {db.meta['version']}. Do not edit.",
        f"-- {what}",
    ]
    lines += [f"-- {line}".rstrip() for line in legend]
    lines += ["local _, ns = ...", "ns.data = ns.data or {}"]
    return lines


def encode_entry(entry: ladders.Entry) -> str:
    flags = entry.side
    flags += "s" if entry.seen else ""
    flags += "n" if entry.new else ""
    flags += "u" if entry.unsourced else ""
    flags += "U" if entry.unique else ""
    flags += "t" if entry.two_hand else ""
    flags += "r" if entry.random else ""
    flags += "p" if entry.pvp else ""
    flags += str(entry.phase) if entry.phase else ""
    limit = entry.limit or ""
    if not limit.isalnum() and limit:
        raise ValueError(f"unexpected character in the limit category {limit!r}")
    fields = [str(entry.item_id), str(entry.stored), flags,
              str(entry.twin) if entry.twin else "", limit]
    while fields and not fields[-1]:
        fields.pop()
    return ":".join(fields)


def _corrections_note(db) -> tuple:
    """Says what the lists rank differently from ForeverDB's data, when a correction is in use (corrections.py)."""
    lines = []
    fixes = db.corrected
    if fixes and fixes.changed:
        lines += [f"Changed from ForeverDB's data: {len(fixes.changed)} caster weapons are ranked with the healing, "
                  f"spell damage and damage per second read in the game (build {', '.join(sorted(fixes.builds))}),",
                  "which the data lacks; see _build/corrections.py."]
    game = getattr(db, "aligned", None)
    if game and game.changed:
        lines += [f"Changed from ForeverDB's lists, from what the game showed (build {game.build}): {len(game.dropped)} "
                  f"items the game does not have are left out,",
                  f"and {len(game.added)} pieces it has that ForeverDB does not list are added, flagged u (no known "
                  "source) and 9 (counted once every phase is)."]
    lines += _sources_note(db)
    return tuple(lines)


def _sources_note(db) -> list:
    """Says which sources are not ForeverDB's, when some were read in QuestieDB (corrections.fill)."""
    filled = getattr(db, "filled", None)
    if not filled or not filled.changed:
        return []
    return [f"Added to ForeverDB's data: {len(filled.items)} items and {len(filled.enchants)} enchants it gives no "
            f"source have the one read in QuestieDB {filled.version}",
            "(https://github.com/Questie/QuestieDB, GPL-3.0), labelled t. An item of ForeverDB's lists counts from "
            "the phase that source needs;",
            f"the {len(filled.added)} pieces added from the game among them stay flagged u and 9, with the source "
            "to show. See _build/questie.py."]


def lists_file(db, all_ladders) -> str:
    lines = _header(db, f"Best-in-slot ladders at level {db.meta['cap']}, one text block per class.", (
        *_corrections_note(db),
        "  S <spec> <name> <role> <style>      style: any, 2h, dw (dual wield), shield",
        "  L <spec> <list> <slot> <entries>    list: pve, pvp; entries best first, separated by spaces",
        "An entry is id:score*10:flags:twin:limit, empty fields at the end left out.",
        "  flags: a Alliance only, h Horde only (with a twin: the other faction wears the twin id),",
        "         s seen in Forever, n new in Forever, u no known source, U unique, t two-hander, r random bonus,",
        "         p a PvP reward (a PvP rank, the honor quartermasters, a battleground, a Premier set),",
        "         a digit: the content phase the item needs (none: before the raids, 1: Forever's first raids,",
        "         9: a raid known from Classic data only); see _build/phases.py",
        "  limit: only one item of that category can be worn (rings and trinkets)",
        "A PvP-rank reward is in both lists, ranked on its stats; foreverdb.net/bis leaves those out of its PvE pages.",
    ))
    lines.append("ns.data.lists = {")
    for cls in sorted(all_ladders):
        block = []
        for spec, modes in sorted(all_ladders[cls].items()):
            spec_def = db.classes[cls]["specs"][spec]
            block.append("\t".join(("S", str(spec), spec_def["name"], spec_def["role"], spec_def["style"])))
            for mode in ladders.MODES:
                for slot, _ in ladders.SLOTS:
                    entries = modes[mode][slot]
                    if entries:
                        block.append("\t".join(("L", str(spec), mode, slot, " ".join(map(encode_entry, entries)))))
        lines.append(f"{cls} = {_block(block)},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def shown_ids(all_ladders) -> set[int]:
    ids = set()
    for specs in all_ladders.values():
        for modes in specs.values():
            for slots in modes.values():
                for entries in slots.values():
                    for entry in entries:
                        ids.add(entry.item_id)
                        if entry.twin:
                            ids.add(entry.twin)
    return ids


def _inline_source(db, source: list[str]) -> str:
    """ForeverDB's source text, with a shared vendor (V) written out in full (v)."""
    if source[0] == "V":
        npc, price, side, label = (source + [""] * 5)[1:5]
        vendor = (db.vendors.get(int(npc)) or [""]) + [""] * 4
        source = ["v", npc, vendor[0], vendor[1], vendor[2], vendor[3], price, side, label]
    return "^".join(source)


def items_file(db, all_ladders) -> str:
    rows, instances = [], set()
    for item_id in sorted(shown_ids(all_ladders)):
        item = db.items.get(item_id)
        if item is None:
            continue  # a twin ForeverDB has no line for: the addon falls back to the game's own item data
        sources = phases.shown_sources(item)[:SOURCES_PER_ITEM]  # the first one is what the addon shows
        for source in sources:
            if source[0] == "d" and source[1].isdigit():
                instances.add(int(source[1]))
        text = "~".join(_inline_source(db, source) for source in sources)
        rows.append("|".join((str(item_id), _field(item["name"]), "".join(sorted(item["groups"])),
                              item["flags"], _field(text))))

    lines = _header(db, "Where each listed item comes from: id|name|groups|flags|source~source", (
        *_sources_note(db),
        "  groups: q quest, Q dungeon quest, v vendor, c crafted, d dungeon boss, r raid, w world drop, R rare,",
        "          p PvP rank, e reputation, x container, u no known source",
        "  flags:  s seen in Forever, n new in Forever, r random bonus, U unique",
        "A source is kind^fields^label:",
        "  q^quest^title^level^side^label[^uiMap^x^y^spot label]    v^npc^name^uiMap^x^y^copper^side^label",
        "  d^instance^boss^percent^raid^label                       m^npc^name^percent^label (a creature)",
        "  R^npc^name^percent^label (a rare)                        c^profession^skill^spell^label",
        "  w^level from^level to^label (world drop)                 o^chest^percent^label",
        "  x^item^container^label                                   p^rank^side^label",
        "  r^faction^standing^name^label",
        "  label: s Seen in Forever, c Clue (unconfirmed), f Forever client, k Classic data, t QuestieDB",
    ))
    lines.append(f"ns.data.items = {_block(rows)}")
    lines.append("-- Instances: name^kind^uiMap of the entrance^zone")
    lines.append("ns.data.instances = {")
    for instance in sorted(instances):
        fields = db.instances.get(instance)
        if fields:
            fields = fields + [""] * 6
            value = "^".join((fields[0], fields[1], fields[2], fields[5]))
            if '"' in value or "\\" in value:
                raise ValueError(f"unexpected character in instance {instance}")
            lines.append(f'[{instance}]="{value}",')
    lines.append("}")
    return "\n".join(lines) + "\n"


def names_file(db) -> str:
    """Every item ForeverDB knows that is worn, for the add dialog's search by name."""
    rows = []
    for item_id in sorted(db.items):
        gear, name = db.gear.get(item_id), db.items[item_id].get("name")
        if gear is None or not name:
            continue
        if db.items[item_id].get("added"):
            continue  # a piece added from the game (corrections.align): the search is still ForeverDB's names
        rows.append("|".join((str(item_id), str(gear["req"] or ""), _field(name))))
    lines = _header(db, "The items to wear, for the search by name: id|required level|English name")
    lines.append(f"ns.data.names = {_block(rows)}")
    return "\n".join(lines) + "\n"


# The enchant keys that go on one kind of item only: (Easy BIS slots to look in, what the item has to be).
# ForeverDB lists them for every class; a spec keeps the ones its lists hold an item for.
_ENCHANT_GOES_ON = {
    "w1h": (("main", "off"), lambda gear: gear["inv"] in (13, 21, 22)),            # one-hand, main hand, off hand
    "w2h": (("main",), lambda gear: gear["inv"] == 17),
    "shield": (("off",), lambda gear: gear["inv"] == 14),
    "held": (("off",), lambda gear: gear["inv"] == 23),
    "rng": (("ranged",), lambda gear: gear["inv"] in (15, 26) and not gear["wand"]),  # bow, gun or crossbow
}


def enchant_fits(db, key: str, spec_ladders: dict) -> bool:
    """Whether the spec's PvE list ({mode: {slot: [Entry]}}) holds an item this enchant key goes on.

    The enchants are ForeverDB's PvE ("raid") ones, so the PvE list decides. A piece added from the game
    (corrections.align) does not count: it shows only with the items of no known source, and an enchant
    row is shown whatever the options.
    """
    if key not in _ENCHANT_GOES_ON:
        return True  # an armor slot: every spec fills it
    slots, fits = _ENCHANT_GOES_ON[key]
    for slot in slots:
        for entry in spec_ladders["pve"][slot]:
            gear = db.gear.get(entry.item_id)
            if gear and fits(gear) and not db.items.get(entry.item_id, {}).get("added"):
                return True
    return False


def enchant_ladders(db, cls: str, spec: int, spec_ladders: dict) -> dict[str, list[tuple[str, int]]]:
    """{slot key: [(enchant, phase)], best first}: what the addon needs to show a level-cap character of
    that spec its ENCHANTS_PER_SLOT best enchants, whatever the content phase."""
    per_slot = db.enchants.get(cls, {}).get((spec, "raid"), {})
    cap = db.meta["cap"]
    out = {}
    for key, entries in per_slot.items():
        if not enchant_fits(db, key, spec_ladders):
            continue
        usable = [(enchant, phases.enchant_phase(db, enchant)) for enchant, level in entries
                  if level <= cap and enchant in db.enchant_info]
        keep = set()
        for phase in phases.PHASES:
            keep.update([pair for pair in usable if pair[1] <= phase][:ENCHANTS_PER_SLOT])
        if keep:
            out[key] = [pair for pair in usable if pair in keep]
    return out


def best_enchants(ladder: dict[str, list[tuple[str, int]]], phase: int) -> dict[str, list[str]]:
    """{slot key: enchants, best first} shown at a content phase, from enchant_ladders' result."""
    out = {}
    for key, pairs in ladder.items():
        shown = [enchant for enchant, needed in pairs if needed <= phase][:ENCHANTS_PER_SLOT]
        if shown:
            out[key] = shown
    return out


def enchants_file(db, all_ladders) -> str:
    used = set()
    lines = _header(db, f"The best enchant, armor kit or scope per spec and slot at level {db.meta['cap']}.", (
        *_sources_note(db),
        "  E <spec> <slot key> <ids>    ids best first; s<spell id> an enchant, i<item id> a kit, spike or scope;",
        "                               id:<phase> when it needs a raid (as in Lists.lua; see _build/phases.py)",
        "  slot keys: head neck shoulder back chest wrist hands legs feet, w1h w2h (weapons), shield, held, rng",
        f"An item takes only one of them. The addon shows the first {ENCHANTS_PER_SLOT} of the character's phase.",
        "A weapon, shield, held or ranged key is listed only for the specs whose PvE list holds such an item.",
    ))
    lines.append("ns.data.enchants = {")
    for cls in sorted(db.classes):
        block = []
        for spec in sorted(db.classes[cls]["specs"]):
            ladder = enchant_ladders(db, cls, spec, all_ladders[cls][spec])
            for key, pairs in sorted(ladder.items()):
                used.update(enchant for enchant, _ in pairs)
                tokens = [f"{enchant}:{phase}" if phase else enchant for enchant, phase in pairs]
                block.append("\t".join(("E", str(spec), key, " ".join(tokens))))
        lines.append(f"{cls} = {_block(block)},")
    lines.append("}")
    lines.append("-- id|name|effect|where it comes from|label (s Seen in Forever, c Clue, f Forever client, k Classic data,")
    lines.append("-- t QuestieDB: \"Quest: <title> (<instance>)\", \"Raid drop: <boss>\", \"Vendor: <name>\"..., see _build/questie.py)")
    rows = ["|".join([enchant] + [_field(text) for text in (db.enchant_info[enchant] + [""] * 4)[:4]])
            for enchant in sorted(used)]
    lines.append(f"ns.data.enchantInfo = {_block(rows)}")
    return "\n".join(lines) + "\n"


def meta_file(db) -> str:
    lines = _header(db, "What the data files were built from.")
    lines.append("ns.data.meta = {")
    lines.append(f'    level = {db.meta["cap"]},')
    lines.append(f'    build = "{db.meta["build"]}",')
    lines.append(f'    version = "{db.meta["version"]}",')
    lines.append(f'    credit = "{CREDIT}",')
    lines.append('    lists = { "pve", "pvp" },')
    lines.append("    -- content phases a list can stop at: 0 before the raids, 9 everything the data holds")
    lines.append(f'    phases = {{ {", ".join(map(str, phases.PHASES))} }},')
    lines.append(f"    phase = {phases.CURRENT},  -- the phase the game is in")
    lines.append(f"    alternatives = {ladders.MAX_ALTERNATIVES},  -- picks the lists keep after the best one(s) of a slot")
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_all(db, all_ladders, out_dir) -> dict[str, int]:
    """Write the five data files; returns {file name: size in bytes}."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    files = {
        "Meta.lua": meta_file(db),
        "Lists.lua": lists_file(db, all_ladders),
        "Items.lua": items_file(db, all_ladders),
        "Enchants.lua": enchants_file(db, all_ladders),
        "Names.lua": names_file(db),
    }
    sizes = {}
    for name, text in files.items():
        data = text.encode("utf-8")
        (out_dir / name).write_bytes(data)
        sizes[name] = len(data)
    return sizes
